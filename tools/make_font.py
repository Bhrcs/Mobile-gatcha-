SPACE_ADVANCE = 4


def glyph_name(ch):
    if ch.isalnum() and ord(ch) < 128:
        return ch if not ch.isdigit() else "digit" + ch
    return "uni%04X" % ord(ch)


def build_glyph(rows):
    """Converts pixel rows into a TrueType outline, merging horizontal runs."""
    pen = TTGlyphPen(None)
    width = max(len(r) for r in rows)
    for r_index, row in enumerate(rows):
        y_top = (7 - r_index) * PX
        y_bot = y_top - PX
        x = 0
        while x < len(row):
            if row[x] == '#':
                start = x
                while x < len(row) and row[x] == '#':
                    x += 1
                x0, x1 = start * PX, x * PX
                # Clockwise contour (TrueType outer contour)
                pen.moveTo((x0, y_bot))
                pen.lineTo((x0, y_top))
                pen.lineTo((x1, y_top))
                pen.lineTo((x1, y_bot))
                pen.closePath()
            else:
                x += 1
    return pen.glyph(), (width + 1) * PX


def main():
    order = [".notdef", "space"]
    glyphs = {}
    metrics = {}
    cmap = {32: "space"}

    empty = TTGlyphPen(None).glyph()
    glyphs[".notdef"] = empty
    metrics[".notdef"] = (SPACE_ADVANCE * PX, 0)
    glyphs["space"] = TTGlyphPen(None).glyph()
    metrics["space"] = (SPACE_ADVANCE * PX, 0)

    for ch, rows in G.items():
        name = glyph_name(ch)
        glyph, adv = build_glyph(rows)
        glyphs[name] = glyph
        metrics[name] = (adv, 0)
        cmap[ord(ch)] = name
        order.append(name)

    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT)
    fb.setupNameTable({"familyName": "Cinder Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=100,
                usWinAscent=ASCENT, usWinDescent=DESCENT)
    fb.setupPost()
    out = os.path.join(os.path.dirname(__file__), "..", "assets", "fonts", "cinder_pixel.ttf")
    fb.save(out)
    print("wrote", os.path.abspath(out), len(G), "glyphs")


if __name__ == "__main__":
    main()
